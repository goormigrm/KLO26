// ⚠ 온라인 대전에서 두 브라우저가 **같은 결과**를 얻어야 한다. 그래서 난수를 그 자리에서 뽑지 않고
// **경기 시드에서 유도**한다 — 시드는 두 스쿼드 코드와 방 코드로 만들어(DESIGN 4.11) 양쪽이 이미 같은 값을 갖고 있다.
// 누구도 고를 수 없고, 결과 링크를 다시 열어도 같은 팀이 홈이다.

import { makeRng, rand } from '../core/rng'

/**
 * 이 시드에서 **방장(혼자 하기면 사람)이 홈인가**.
 * 시드를 그대로 쓰지 않고 한 번 섞는다 — 시드의 낮은 비트가 다른 곳(상대 구단 고르기 `seed % CLUBS.length`)에도 쓰여
 * 두 값이 함께 움직이면 "특정 구단이 늘 원정" 같은 편향이 생긴다.
 */
export function tossHostHome(seed: number): boolean {
  return rand(makeRng((seed ^ 0x5f356495) >>> 0)) < 0.5
}
